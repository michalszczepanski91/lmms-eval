#!/usr/bin/env python3
"""Write results/<board>/REPORT_qwen2_5.md: every table of the text-only Qwen2.5 study, generated from the result files.

Sections: Phase 1 tables per size and task (analyze.py), the Q1 rule (as fixed and with the 1-point sensitivity check),
repeats, the bandwidth / sweep / weight-study tables (figures.py, which also redraws the figures), and the cost of
building each Edge-LLM engine (build_info.txt from ensure_engines.sh). FINDINGS_qwen2_5.md quotes these numbers.

Usage: python3 jetson/experiments/qwen2_5/report.py
"""

import contextlib
import glob
import io
import os
import sys

HERE = os.path.dirname(os.path.abspath(__file__))
sys.path.insert(0, HERE)
import analyze as A  # noqa: E402
import figures as F  # noqa: E402

TASK_TITLE = {"gsm8k_jetson": "GSM8K (5-shot, 1,319 questions)", "mmlu_jetson": "MMLU (5-shot generative, 14,042 questions)", "ifeval": "IFEval (541 prompts)"}


def captured(fn, *args, **kwargs):
    buf = io.StringIO()
    with contextlib.redirect_stdout(buf):
        fn(*args, **kwargs)
    return [line for line in buf.getvalue().splitlines() if not line.startswith("wrote ")]


def build_table():
    rows = ["| Engine | Quantize (s) | Export incl. quantize (s) | Build (s) | Peak memory, export / build (GB) | Engine dir (GB) |", "|---|---:|---:|---:|---:|---:|"]
    for path in sorted(glob.glob(os.path.join(F.TRT_WORKSPACE, "Qwen2.5-*B-Instruct-*", "build_info.txt"))):
        name = os.path.basename(os.path.dirname(path))
        if "-VL-" in name:
            continue
        info = dict(line.strip().split("=", 1) for line in open(path) if "=" in line)
        built = os.path.exists(os.path.join(os.path.dirname(path), "engines", "llm", "llm.engine"))
        size = f"{int(info['engine_bytes']) / 1e9:.2f}" if built and "engine_bytes" in info else "build failed"
        rows.append(f"| {name.replace('Qwen2.5-', '').replace('-Instruct', '')} | {info.get('quantize_seconds', '–')} | {info.get('export_seconds', '–')} | {info.get('build_seconds', '–')} | {info.get('export_peak_used_gb', '–')} / {info.get('build_peak_used_gb', '–')} | {size} |")
    return rows


def main():
    sizes, tasks = list(A.SIZES), A.TASKS
    table = A.collect(sizes, tasks)
    out = [
        "# Text-only Qwen2.5-Instruct on Jetson Thor: detailed results",
        "",
        "Qwen2.5-1.5B / 3B-Instruct (text only) across HF transformers, vLLM, llama.cpp and TensorRT Edge-LLM, on GSM8K, MMLU and IFEval, plus a",
        "controlled-length sweep and a study of Edge-LLM weight configurations. **Generated by `python3 jetson/experiments/qwen2_5/report.py`** from the",
        "result files; edit the scripts, not this file.",
        "",
        "- The conclusions in plain words: [FINDINGS_qwen2_5.md](FINDINGS_qwen2_5.md). Plan, decisions, problems: [NOTES_qwen2_5.md](NOTES_qwen2_5.md).",
        "- Every run, including excluded ones: [SUMMARY.md](SUMMARY.md). How each metric is measured: [methodology](../../docs/methodology.md#text-only-models).",
        "",
        "**For all tables:** power mode MAXN, batch 1, greedy, no repetition penalty, prefix caching off, nothing else on the GPU. Accuracy: GSM8K",
        "flexible-extract, MMLU first A–D letter (all subjects), IFEval prompt-level strict. Δ vs HF = paired difference to HF bf16 on the same questions",
        "± its standard error; ✗ = more than 2 SE below HF (the accuracy rule). Time / energy per question include each framework's own answer length.",
        "TTFT p50: per-request median; Edge-LLM (*): median prefill GPU time from its runner profile, without host overhead.",
        "",
        "## 1. Frameworks (Phase 1)",
    ]
    for size in ("3b", "1.5b"):
        for task in tasks:
            lines = captured(A.print_tables, {(size, task): table[(size, task)]})
            lines = [line for line in lines if not line.startswith("✗ = fails") and not line.startswith("### ")]
            out += ["", f"### {A.SIZES[size]} · {TASK_TITLE[task]}", ""] + [line for line in lines if line.strip()]
    out += ["", "## 2. The Q1 rule", "", "Rule fixed before Phase 1 ([NOTES_qwen2_5.md](NOTES_qwen2_5.md#plan-written-2026-10-08-before-building)); the verdict is in the notes.", ""]
    out += [line for line in captured(A.q1, table, sizes, tasks) if not line.startswith("## Q1")]
    tol = A.collect(sizes, tasks, min_tolerance=1.0)
    q1_tol = captured(A.q1, tol, sizes, tasks)
    start = next(i for i, line in enumerate(q1_tol) if line.startswith("Edge-LLM best or tied"))
    out += ["", "**Sensitivity check** (accuracy rule passes Δ ≥ −max(2 SE, 1 point); NOTES decision 16):", ""] + q1_tol[start:]
    out += ["", "## 3. Repeats on a different day", ""] + [line for line in captured(A.print_repeats, table) if not line.startswith("## ")]
    out += ["", "## 4. Decode against the memory-bandwidth floor (GSM8K)", "", "![bandwidth](qwen2_5_bandwidth.png)", ""] + captured(F.bandwidth, os.path.join(A.RESULTS, "qwen2_5_bandwidth.svg"))
    out += ["", "## 5. Controlled-length sweep", "", "16 prompts per length, 256 generated tokens ([methodology](../../docs/methodology.md#text-only-models)).", "", "![sweep](qwen2_5_sweep.png)", ""]
    out += captured(F.sweep, os.path.join(A.RESULTS, "qwen2_5_sweep.svg"))
    out += ["", "## 6. TensorRT Edge-LLM weight configurations (Phase 2)", "", "![weight study](qwen2_5_pareto.png)", ""] + captured(F.pareto, os.path.join(A.RESULTS, "qwen2_5_pareto.svg"))
    out += [
        "",
        "Not in the table (rows of FINDINGS_qwen2_5.md): nvfp4, int4 LM head (`int4_awq_lmhead`) and Qwen's AWQ import (`int4_awq_qwen`, `int4_awq_qwen_v1`)",
        "give garbage text in the smoke tests; mxfp8 cannot be built (TensorRT: E8M0 is not supported in plugins); Qwen's GPTQ-Int8 cannot be imported",
        "(the exporter reads every GPTQ checkpoint as int4).",
        "",
        "### Cost of building each engine",
        "",
        "From `build_info.txt` (ensure_engines.sh). Peak memory is the whole board's (CPU and GPU share it). The 3B fp16 / fp8 / int4_awq engines were built",
        "before this was recorded (3B fp16: 2 min 44 s build).",
        "",
    ] + build_table()
    path = os.path.join(A.RESULTS, "REPORT_qwen2_5.md")
    open(path, "w").write("\n".join(out) + "\n")
    print("wrote", path)


if __name__ == "__main__":
    main()
